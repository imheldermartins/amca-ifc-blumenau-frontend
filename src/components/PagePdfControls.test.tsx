import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { PdfExportContent } from './PagePdfControls'
const api = vi.hoisted(() => ({ generate: vi.fn() }))
vi.mock('@/services/PagePdfService', () => ({ pagePdfService: api }))
vi.mock('./PdfPreview', () => ({ default: ({ file }: { file: Blob }) => <div data-testid="pdf-preview" data-bytes={file.size} /> }))
beforeEach(() => {
  api.generate.mockImplementation(async (_pageId: string, ids?: string[]) => ids && ids.length > 1
    ? { blob: new Blob(['ZIP']), filename: 'lotes.zip' }
    : { blob: new Blob(['%PDF']), filename: 'lote-0001.pdf' })
  vi.stubGlobal('URL', { createObjectURL: vi.fn(() => 'blob:download'), revokeObjectURL: vi.fn() })
})
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.clearAllMocks() })
function mount(ids?: string[], beforeGenerate?: () => Promise<void>) { return render(<PdfExportContent pageId="current" selectedIds={ids} beforeGenerate={beforeGenerate} />) }
describe('PDF modal', () => {
  it('opens directly in preview with the filename, title switch and one download action', async () => {
    mount()
    expect(screen.queryByRole('button', { name: 'Visualizar PDF' })).toBeNull()
    await screen.findByTestId('pdf-preview')
    expect(screen.getByText('lote-0001.pdf')).toBeTruthy()
    expect(api.generate).toHaveBeenCalledWith('current', undefined, { includePageTitle: true })
    fireEvent.click(screen.getByRole('switch', { name: 'Incluir título da página' }))
    await waitFor(() => expect(api.generate).toHaveBeenCalledWith('current', undefined, { includePageTitle: false }))
    await screen.findByTestId('pdf-preview')
    expect(screen.getByRole('button', { name: 'Baixar PDF' }).previousElementSibling?.getAttribute('class')).toBeTruthy()
  })
  it('generates the complete batch and shows only its centered ZIP confirmation', async () => {
    const flush = vi.fn(async () => {})
    const view = mount(['one', 'two'], flush)
    const success = await screen.findByText('lotes.zip gerado com sucesso')
    expect(flush).toHaveBeenCalledOnce()
    expect(api.generate).toHaveBeenCalledExactlyOnceWith('current', ['one', 'two'], { includePageTitle: true })
    expect(success.parentElement?.className).toContain('place-content-center text-center')
    expect(screen.getByText('lotes.zip')).toBeTruthy()
    expect(screen.queryByTestId('pdf-preview')).toBeNull()
    expect(screen.queryByRole('checkbox')).toBeNull()
    expect(URL.createObjectURL).not.toHaveBeenCalled()
    view.unmount()
    expect(screen.queryByTestId('pdf-preview')).toBeNull()
  })
  it('downloads the generated ZIP without generating a first-row preview or another batch', async () => {
    mount(['one', 'two'])
    await screen.findByText('lotes.zip gerado com sucesso')
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    fireEvent.click(screen.getByRole('button', { name: 'Baixar ZIP' }))
    await waitFor(() => expect(api.generate).toHaveBeenCalledExactlyOnceWith('current', ['one', 'two'], { includePageTitle: true }))
    expect(click).toHaveBeenCalledOnce()
    click.mockRestore()
  })
  it('previews and downloads a single selected page using the selection template', async () => {
    mount(['one'])
    await screen.findByTestId('pdf-preview')
    expect(api.generate).toHaveBeenCalledExactlyOnceWith('current', ['one'], { includePageTitle: true })
    expect(screen.queryByText(/gerado com sucesso/)).toBeNull()
    expect(screen.queryByRole('button', { name: 'Baixar ZIP' })).toBeNull()
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    fireEvent.click(screen.getByRole('button', { name: 'Baixar PDF' }))
    await waitFor(() => expect(click).toHaveBeenCalledOnce())
    expect(api.generate).toHaveBeenCalledOnce()
    click.mockRestore()
  })
  it('regenerates all selected pages when the title switch changes and never renders a batch preview', async () => {
    mount(['one', 'two'])
    await screen.findByText('lotes.zip gerado com sucesso')
    fireEvent.click(screen.getByRole('switch', { name: 'Incluir título da página' }))
    await waitFor(() => expect(api.generate).toHaveBeenLastCalledWith('current', ['one', 'two'], { includePageTitle: false }))
    await screen.findByText('lotes.zip gerado com sucesso')
    expect(api.generate).toHaveBeenCalledTimes(2)
    expect(screen.queryByTestId('pdf-preview')).toBeNull()
  })
  it('does not show ZIP success on failure and retries the complete selection', async () => {
    api.generate.mockRejectedValueOnce(new Error('offline'))
    mount(['one', 'two'])
    await screen.findByRole('alert')
    expect(screen.queryByText(/gerado com sucesso/)).toBeNull()
    expect((screen.getByRole('button', { name: 'Baixar ZIP' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Tentar novamente' }))
    await screen.findByText('lotes.zip gerado com sucesso')
    expect(api.generate).toHaveBeenLastCalledWith('current', ['one', 'two'], { includePageTitle: true })
    expect(screen.queryByTestId('pdf-preview')).toBeNull()
  })
  it('keeps the current-page export independent of an earlier pending selection', async () => {
    let finish!: (file: { blob: Blob; filename: string }) => void
    api.generate.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
    const view = mount(['one', 'two'])
    await waitFor(() => expect(api.generate).toHaveBeenCalledOnce())
    view.rerender(<PdfExportContent pageId="opened-page" />)
    await screen.findByTestId('pdf-preview')
    expect(api.generate).toHaveBeenLastCalledWith('opened-page', undefined, { includePageTitle: true })
    await act(async () => finish({ blob: new Blob(['ZIP']), filename: 'old.zip' }))
    expect(screen.getByText('lote-0001.pdf')).toBeTruthy()
    expect(screen.queryByText('old.zip')).toBeNull()
    expect(screen.queryByRole('button', { name: 'Baixar ZIP' })).toBeNull()
  })
  it('downloads the current document without consulting the parent or generating a second preview', async () => {
    mount()
    await screen.findByTestId('pdf-preview')
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    fireEvent.click(screen.getByRole('button', { name: 'Baixar PDF' }))
    await waitFor(() => expect(click).toHaveBeenCalledOnce())
    expect(api.generate).toHaveBeenCalledOnce()
    expect(api.generate).toHaveBeenCalledWith('current', undefined, { includePageTitle: true })
    click.mockRestore()
  })
  it('blocks selections over the batch limit', async () => {
    mount(Array.from({ length: 51 }, (_, index) => String(index)))
    expect((screen.getByRole('button', { name: 'Baixar ZIP' }) as HTMLButtonElement).disabled).toBe(true)
    expect(await screen.findByRole('alert')).toBeTruthy()
    expect(api.generate).not.toHaveBeenCalled()
  })
})
